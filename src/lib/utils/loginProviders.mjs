// Якими дверима справді можна зайти — одним списком.
//
// Екран входу й розділ «Способи входу» в налаштуваннях відповідали на це
// питання нарізно й розійшлися. Клієнтський вхід малює одну кнопку — Google:
// GitHub стоїть за прапорцем, який вимкнений, а OneB намальований під
// `!clientLogin`, бо це вхід служби підтримки. Розділ у налаштуваннях, який
// рендериться *тільки клієнтам*, пропонував підключити всі три. Підключений
// провайдер, яким потім не можна увійти, — це не налаштування, а запрошення
// спробувати й повернутися ні з чим.
//
// Прапорець жив у трьох файлах трьома копіями одного рядка. Тут він один.

export const GITHUB_LOGIN_ENABLED = process.env.NEXT_PUBLIC_GITHUB_LOGIN_ENABLED === 'true';

/**
 * Чи може клієнтське місце відкрити цим провайдером свій акаунт.
 *
 * Це не «чи вміє Firebase привʼязати такий провайдер» — вміє всі три. Це «чи є
 * на клієнтському екрані входу кнопка, яка ним заходить», і відповідь дає той
 * екран, а не список можливостей бібліотеки.
 */
export const CLIENT_LOGIN_PROVIDERS = Object.freeze({
  google: true,
  github: GITHUB_LOGIN_ENABLED,
  // Вхід через OneB — службовий: `/login` показує його лише поза клієнтським
  // режимом. Доки це так, клієнтові немає що тут підключати.
  oneb: false,
});
